public class mult {
    public static void main(String[] args) {
        int num[][]={
            {1,2,2},
            {3,4,5},
            {9,4,5}
        };

        for (int i=0;i<num.length;i++){
            System.out.println(" ");
            for(int j=0;j<num[i].length;j++){
                System.out.print(num[i][j]+ " ");
            }
        }
    }
    
}
