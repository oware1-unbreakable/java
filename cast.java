public class cast {
    public static void main(String[] args){
        int a = 567;
        double b=a;
        System.out.println(b);

        byte c=123;
        int d=(int) c;
        System.out.println(d);

        int f =257;
        byte r=(byte) f;
        System.out.println(r);
    }
    
}

